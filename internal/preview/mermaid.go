package preview

import (
	"bytes"
	"crypto/rand"
	"crypto/sha256"
	"fmt"
	"html"
	"net/http"

	"github.com/yuin/goldmark/ast"
)

// MermaidRuntime contains only trusted product code, never a previewed file.
// It is immutable and shared by all previews for the server's lifetime.
type MermaidRuntime struct {
	url    string
	script []byte
}

// NewMermaidRuntime names a bundled classic script by its content hash.
func NewMermaidRuntime(script []byte) *MermaidRuntime {
	return &MermaidRuntime{
		url:    fmt.Sprintf("/preview-assets/mermaid.%x.js", sha256.Sum256(script)),
		script: append([]byte(nil), script...),
	}
}

// URL returns the immutable product asset's address.
func (m *MermaidRuntime) URL() string { return m.url }

// ServeHTTP serves exactly the bundled asset; there is no filesystem or SPA fallback.
func (m *MermaidRuntime) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if r.URL.Path != m.url {
		http.NotFound(w, r)
		return
	}
	w.Header().Set("Content-Type", "text/javascript; charset=utf-8")
	w.Header().Set("X-Content-Type-Options", "nosniff")
	w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
	_, _ = w.Write(m.script)
}

func hasMermaid(document ast.Node, source []byte) bool {
	found := false
	_ = ast.Walk(document, func(n ast.Node, _ bool) (ast.WalkStatus, error) {
		if block, ok := n.(*ast.FencedCodeBlock); ok && string(block.Language(source)) == "mermaid" {
			found = true
			return ast.WalkStop, nil
		}
		return ast.WalkContinue, nil
	})
	return found
}

func (m *MermaidRuntime) enable(page []byte) ([]byte, string) {
	nonce := rand.Text()
	policy := "sandbox allow-scripts; default-src 'none'; script-src 'nonce-" + nonce + "'; script-src-attr 'none'; " +
		"connect-src 'none'; object-src 'none'; frame-src 'none'; worker-src 'none'; base-uri 'none'; " +
		"form-action 'none'; img-src * data:; style-src 'unsafe-inline'; frame-ancestors 'self'"
	// The only interpolated values are generated by the product. Markdown is
	// already escaped by goldmark and is never placed in this script element.
	script := `<script defer nonce="` + nonce + `" src="` + html.EscapeString(m.url) + `"></script>`
	return bytes.Replace(page, []byte("</body>"), []byte(script+"</body>"), 1), policy
}
